/**
 * Scenes are standalone HyperFrames compositions (05-scenes/<id>.html). `yt scene build` turns one into a
 * self-contained project dir (kit + vendored fonts/GSAP + scene assets), so renders are offline and
 * reproducible, and each scene can be rendered, cached and checked on its own.
 */
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { channel } from "./config";
import { hyperframes, run, runPreview } from "./lib/exec";
import { ensureDir, load, round, writeJson, writeText } from "./lib/io";
import { ep, KIT, PIPELINE } from "./lib/paths";
import { Storyboard, Timing } from "./schemas";
import { sceneWindows, type SceneWindow } from "./timing";

const CUES_RE = /\/\* @cues:begin[\s\S]*?@cues:end \*\//;
const ROOT_DUR_RE = /(id="scene-root"[^>]*?data-duration=")([\d.]+)(")/;

export function windows(slug: string): { timing: Timing; storyboard: Storyboard; windows: SceneWindow[] } {
  const p = ep(slug);
  const timing = load(Timing, p.timing);
  const storyboard = load(Storyboard, p.storyboard);
  return { timing, storyboard, windows: sceneWindows(storyboard, timing, channel().video.fps) };
}

/** The CUES object a scene sees: its own beats, with times relative to the scene start. */
export function sceneCues(timing: Timing, win: SceneWindow) {
  const beats: Record<string, { start: number; end: number; speech_end: number; words: [string, number][] }> = {};
  for (const id of win.beats) {
    const b = timing.beats.find((x) => x.id === id)!;
    beats[id] = {
      start: round(b.start - win.start),
      end: round(b.end - win.start),
      speech_end: round(b.speech_end - win.start),
      words: b.words.map((w) => [w.w, round(w.start - win.start)]),
    };
  }
  return { scene: win.id, duration: win.duration, beats };
}

function cuesBlock(cues: unknown) {
  return `/* @cues:begin — generated by \`yt scene retime\`; do not edit by hand */\n      const CUES = ${JSON.stringify(cues)};\n      /* @cues:end */`;
}

/** Create 05-scenes/<id>.html from the template (no-op if it exists). */
export function scaffoldScene(slug: string, sceneId: string): string {
  const { timing, storyboard, windows: wins } = windows(slug);
  const win = wins.find((w) => w.id === sceneId);
  if (!win) throw new Error(`unknown scene ${sceneId}`);
  const scene = storyboard.scenes.find((s) => s.id === sceneId)!;
  const file = ep(slug).scene(sceneId);
  if (existsSync(file)) return file;
  const html = readFileSync(join(KIT, "templates", "scene.html"), "utf8")
    .replaceAll("{{ID}}", sceneId)
    .replaceAll("{{DURATION}}", String(win.duration))
    .replaceAll("{{CONCEPT}}", scene.concept.replaceAll("--", "—"))
    .replace(CUES_RE, cuesBlock(sceneCues(timing, win)));
  writeText(file, html);
  return file;
}

/** Rewrite every scene's CUES block and root duration from the current timing (after a voice change). */
export function retimeScenes(slug: string): { id: string; changed: boolean }[] {
  const { timing, windows: wins } = windows(slug);
  return wins.map((win) => {
    const file = ep(slug).scene(win.id);
    if (!existsSync(file)) return { id: win.id, changed: false };
    const before = readFileSync(file, "utf8");
    if (!CUES_RE.test(before)) throw new Error(`${file} has no @cues block`);
    // Clips that span the whole scene share the root's duration; move them together.
    const oldDur = ROOT_DUR_RE.exec(before)?.[2];
    let after = before.replace(CUES_RE, cuesBlock(sceneCues(timing, win)));
    if (oldDur) after = after.replaceAll(`data-duration="${oldDur}"`, `data-duration="${win.duration}"`);
    if (after !== before) writeFileSync(file, after);
    return { id: win.id, changed: after !== before };
  });
}

/** Copy kit + vendored fonts and GSAP into `dir/kit`. */
export function installKit(dir: string) {
  const kitDir = join(dir, "kit");
  ensureDir(join(kitDir, "vendor"));
  for (const f of ["kit.css", "kit.js"]) cpSync(join(KIT, f), join(kitDir, f));
  const nm = join(PIPELINE, "node_modules");
  const vendor: [string, string][] = [
    [join(nm, "gsap", "dist", "gsap.min.js"), "gsap.min.js"],
    [join(nm, "@fontsource-variable", "inter", "files", "inter-latin-wght-normal.woff2"), "inter.woff2"],
    [join(nm, "@fontsource-variable", "fredoka", "files", "fredoka-latin-wght-normal.woff2"), "fredoka.woff2"],
  ];
  for (const [src, name] of vendor) {
    if (!existsSync(src)) throw new Error(`missing ${src}; run \`bun install\` in pipeline/`);
    cpSync(src, join(kitDir, "vendor", name));
  }
}

/** Build a self-contained HyperFrames project for one composition file. */
export function buildProject(srcHtml: string, dir: string, assetsDir?: string) {
  rmSync(dir, { recursive: true, force: true });
  ensureDir(dir);
  cpSync(srcHtml, join(dir, "index.html"));
  installKit(dir);
  if (assetsDir && existsSync(assetsDir)) cpSync(assetsDir, join(dir, "assets"), { recursive: true });
  writeJson(join(dir, "hyperframes.json"), {
    $schema: "https://hyperframes.heygen.com/schema/hyperframes.json",
    paths: { blocks: "compositions", components: "compositions/components", assets: "assets" },
    media: { autoProxy: true },
  });
  writeJson(join(dir, "meta.json"), { id: dir.split("/").at(-1), name: dir.split("/").at(-1) });
  return dir;
}

export function buildScene(slug: string, sceneId: string): string {
  const p = ep(slug);
  if (!existsSync(p.scene(sceneId))) throw new Error(`missing ${p.scene(sceneId)}; run \`yt scene scaffold ${slug} ${sceneId}\``);
  return buildProject(p.scene(sceneId), p.sceneBuild(sceneId), p.sceneAssets(sceneId));
}

export interface SceneCheck {
  scene: string;
  ok: boolean;
  duration: { expected: number; declared: number | null; ok: boolean };
  hyperframes: { ok: boolean; errors: number; warnings: number; output: string };
  snapshots: string[];
  contact_sheet?: string;
}

/** hyperframes check (lint, runtime, layout, motion, contrast) + duration lock + snapshots/contact sheet. */
export async function checkScene(slug: string, sceneId: string, opts: { frames?: number } = {}): Promise<SceneCheck> {
  const p = ep(slug);
  const { windows: wins } = windows(slug);
  const win = wins.find((w) => w.id === sceneId);
  if (!win) throw new Error(`unknown scene ${sceneId}`);
  const dir = buildScene(slug, sceneId);

  const html = readFileSync(join(dir, "index.html"), "utf8");
  const declared = Number(ROOT_DUR_RE.exec(html)?.[2] ?? Number.NaN);
  const durationOk = Math.abs(declared - win.duration) < 1 / 30 + 1e-6;

  const res = await runPreview([...hyperframes(), "check", dir], { allowFail: true });
  const output = (res.stdout + res.stderr).replace(/\x1b\[[0-9;]*m/g, "");
  const errors = [...output.matchAll(/(\d+) error\(s\)|(\d+) errors?,/g)].reduce((a, m) => a + Number(m[1] ?? m[2] ?? 0), 0);
  const warnings = [...output.matchAll(/(\d+) warning\(s\)|(\d+) warnings?\b/g)].reduce((a, m) => a + Number(m[1] ?? m[2] ?? 0), 0);

  const snapDir = join(p.qa, "scenes", sceneId);
  rmSync(snapDir, { recursive: true, force: true });
  ensureDir(snapDir);
  await runPreview([...hyperframes(), "snapshot", dir, "--frames", String(opts.frames ?? 6), "-o", snapDir, "--describe", "false"], { allowFail: true });
  const snapshots = existsSync(snapDir) ? readdirSync(snapDir).filter((f) => f.endsWith(".png")).sort().map((f) => join(snapDir, f)) : [];
  let contact: string | undefined;
  if (snapshots.length) {
    contact = join(p.qa, "scenes", `${sceneId}-contact.jpg`);
    await contactSheet(snapshots, contact, 3);
  }
  const check: SceneCheck = {
    scene: sceneId,
    ok: res.code === 0 && durationOk && snapshots.length > 0,
    duration: { expected: win.duration, declared: Number.isNaN(declared) ? null : declared, ok: durationOk },
    hyperframes: { ok: res.code === 0, errors, warnings, output: output.slice(-4000) },
    snapshots,
    contact_sheet: contact,
  };
  writeJson(join(p.qa, "scenes", `${sceneId}-check.json`), check);
  return check;
}

/** Tile images into one JPEG (a contact sheet the critic can read in one look). */
/** Snapshots of a scene at given times (s), e.g. on cue words; queued like every HyperFrames job. */
export async function snapScene(slug: string, sceneId: string, at: number[]): Promise<string[]> {
  if (!at.length || at.some((t) => !Number.isFinite(t))) throw new Error("--at needs times in seconds, e.g. --at 1.2,3.4");
  const dir = buildScene(slug, sceneId);
  const out = join(ep(slug).qa, "scenes", `${sceneId}-at`);
  rmSync(out, { recursive: true, force: true });
  ensureDir(out);
  await runPreview([...hyperframes(), "snapshot", dir, "--at", at.join(","), "-o", out, "--describe", "false"]);
  return readdirSync(out).filter((f) => f.endsWith(".png")).sort().map((f) => join(out, f));
}

export async function contactSheet(images: string[], out: string, cols = 4, width = 480) {
  ensureDir(join(out, ".."));
  const rows = Math.ceil(images.length / cols);
  const inputs = images.flatMap((f) => ["-i", f]);
  const scaled = images.map((_, i) => `[${i}:v]scale=${width}:-2,setsar=1[v${i}]`).join(";");
  const pads = Array.from({ length: rows * cols - images.length }, (_, k) => `color=c=black:s=${width}x${Math.round((width * 9) / 16)}:d=1[p${k}]`);
  const all = [...images.map((_, i) => `[v${i}]`), ...pads.map((_, k) => `[p${k}]`)].join("");
  const layout = Array.from({ length: rows * cols }, (_, i) => `${(i % cols) * width}_${Math.floor(i / cols) * Math.round((width * 9) / 16)}`).join("|");
  const graph = [scaled, ...pads, `${all}xstack=inputs=${rows * cols}:layout=${layout}:fill=black[out]`].filter(Boolean).join(";");
  if (rows * cols === 1) {
    await run(["ffmpeg", "-y", "-v", "error", ...inputs, "-vf", `scale=${width}:-2`, "-frames:v", "1", "-q:v", "3", out]);
    return out;
  }
  await run(["ffmpeg", "-y", "-v", "error", ...inputs, "-filter_complex", graph, "-map", "[out]", "-frames:v", "1", "-q:v", "3", out]);
  return out;
}
