export const PROJECT_GLYPH_NAMES = PROJECT_GLYPH_GROUPS.flatMap(
  (group) => group.names,
) as readonly string[];

/**
 * `grey` first because it is the default on a first pick — an unedited glyph
 * project should look deliberately neutral, not randomly coloured.
 */
export const PROJECT_GLYPH_COLORS = [
  'grey',
  'red',
  'orange',
  'yellow',
  'lime',
  'blue',
  'purple',
  'magenta',
] as const;

export type ProjectGlyphName = (typeof PROJECT_GLYPH_GROUPS)[number]['names'][number];
/** One of the eight preset colours. */
export type ProjectGlyphPaletteColor = (typeof PROJECT_GLYPH_COLORS)[number];

/** A custom colour from the picker's colour field: `#rrggbb`, lower case. */
export type ProjectGlyphHexColor = `#${string}`;

/** A preset name or a custom `#rrggbb` colour. */
export type ProjectGlyphColor = ProjectGlyphPaletteColor | ProjectGlyphHexColor;

const HEX_COLOR = /^#[0-9a-f]{6}$/;

export interface ProjectGlyph {
  name: ProjectGlyphName;
  color: ProjectGlyphColor;
}

const NAME_SET: ReadonlySet<string> = new Set(PROJECT_GLYPH_NAMES);
const COLOR_SET: ReadonlySet<string> = new Set(PROJECT_GLYPH_COLORS);

export function isProjectGlyphName(value: unknown): value is ProjectGlyphName {
  return typeof value === 'string' && NAME_SET.has(value);
}

export function isProjectGlyphPaletteColor(value: unknown): value is ProjectGlyphPaletteColor {
  return typeof value === 'string' && COLOR_SET.has(value);
}

/** Exact match only: a preset name, or `#rrggbb` in lower case. Callers that
 *  accept user input lower-case it first (`normalizeProjectGlyphColor`). */
export function isProjectGlyphColor(value: unknown): value is ProjectGlyphColor {
  return typeof value === 'string' && (COLOR_SET.has(value) || HEX_COLOR.test(value));
}

/** `#AABBCC` -> `#aabbcc`; a preset name passes through; anything else is null. */
export function normalizeProjectGlyphColor(value: unknown): ProjectGlyphColor | null {
  if (typeof value !== 'string') return null;
  const candidate = value.startsWith('#') ? value.toLowerCase() : value;
  return isProjectGlyphColor(candidate) ? candidate : null;
}
