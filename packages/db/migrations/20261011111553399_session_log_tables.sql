-- WHAT: the four tables that store a session as `kortix.session/2` records
-- (packages/api-contract/src/session-log/types.ts), plus one nullable column on
-- kortix.session_turns. No routes and no writers read or write them yet.
--   session_logs          one row per session: the Session without its threads
--   session_log_threads   one row per thread:  the Thread without its messages
--   session_log_messages  one row per message: the whole Message, with blocks
--   session_log_blobs     one row per attachment blob; the bytes live in object storage
--   session_turns.log_durable_at  when the journal ingest acknowledged the turn
--
-- REVIEWED. Generated by `pnpm migrate:generate session_log_tables`; the diff
-- held exactly these objects. Three edits by hand:
--   1. The four ADD FOREIGN KEY statements and the session_turns ADD COLUMN
--      moved to the END, in that order (lock order, below).
--   2. ADDED the REVOKE + ENABLE ROW LEVEL SECURITY block at the bottom, copied
--      from 20260826064400234_session_transcript_mirror.sql.
--   3. This comment.
--
-- INDEX POLICY. Every read is per session, so every index leads with
-- session_id, and there are only three per table at most:
--   * the primary keys: (session_id) / (session_id, thread_id) /
--     (session_id, message_id) / (session_id, sha256);
--   * UNIQUE (session_id, thread_id, seq) on session_log_messages. It is also
--     the index the P4.2 read `GET .../log?thread=&before_seq=&limit=` walks
--     (one thread, seq descending).
-- No single-column index on thread_id, role, kind, in_context or created_at:
-- no query filters on them without session_id. content_hash stays unindexed
-- (learnings 2026-10-01T231554Z: no random-key index on a table that grows
-- with history). No index on project_id/account_id: a project or account
-- deletion reaches these rows through the project_sessions cascade.
-- Retention is the session's lifetime: rows go with the session (CASCADE).
--
-- UNIQUE (session_id, thread_id, seq) is NOT DEFERRABLE. drizzle-orm 0.45 has
-- no way to declare a deferrable unique constraint, and a hand edit here would
-- put the catalog out of step with kortix.ts and its snapshot. A deferrable
-- constraint also cannot be an ON CONFLICT arbiter. The live journal writes
-- native seq values that never shift. A whole-session conversion (P2.7, P3)
-- that re-sequences a thread must DELETE the thread's rows and re-INSERT them
-- in ONE transaction.
--
-- session_log_messages.rev is BIGINT, generation is INT. The daemon journal
-- (P2.4) issues boot-unique revisions as max(Date.now() * 1000, last + 1),
-- about 1.8e15, which overflows int4. The ingest applies the highest rev per
-- message; a tombstone (deleted_at) is a revision too.
--
-- NO FK between session_log_messages and session_log_threads: a journal batch
-- may carry a message put before its thread upsert (P2.2 writes threads first
-- anyway). Message ids are the runtime ids, so session_turns.message_id, the
-- inbox forwarded_message_id and audit_events.message_id join by value; no FK.
-- Each table's FK goes to project_sessions ON DELETE CASCADE. FK names are
-- explicit and under 63 bytes (learnings 2026-09-16T202613Z); every relation is
-- schema-qualified (learnings 2026-10-03T151842Z). Every index above is built
-- here, in the CREATE TABLE, and declared in kortix.ts (learnings
-- 2026-09-25T022801Z; scripts/schema-contract.ts checks it).
--
-- LOCKS. The four tables are new and empty: their constraints need no
-- CONCURRENTLY, no NOT VALID, and no backfill. Two existing hot tables are
-- locked, both until the migrate batch commits:
--   * ADD FOREIGN KEY takes SHARE ROW EXCLUSIVE on kortix.project_sessions
--     (blocks its writes, not its reads or SELECT ... FOR UPDATE).
--   * ADD COLUMN takes ACCESS EXCLUSIVE on kortix.session_turns. A nullable
--     column with no default is catalog-only: no rewrite, no scan.
-- Taken in the writers' order: the stop path and the turn grant lock
-- project_sessions before session_turns (projects/reaping/sandbox-state-sync.ts,
-- projects/sandbox-turn-lifecycle.ts), so this file does too, and both last.
-- The 2 s lock_timeout bounds each wait. On 55P03 the whole batch rolls back:
-- confirm no ledger row and no table, find the holder in pg_stat_activity, and
-- re-run. Never raise the timeout (learnings 2026-09-25T232823Z,
-- 20260930024523072_audit_events_credential_kind.sql).
--
-- MIXED VERSIONS. Old API code never names these tables or the new column, so
-- this can apply before the rollout. Nothing is dropped, renamed or retyped.
--
-- ROLL BACK: no down migration (repo policy). The tables stay empty and unread
-- by old code. To drop them, write a new forward migration.

