// Writes src/components/iam/audit-title-translation-keys.generated.ts: every
// audit title the web shows, mapped to its `hardcodedUi.i18nComplete` key.
//
// A key is `text` + the first 12 hex digits of the title's SHA-256, the
// scheme every `i18nComplete` string uses. The titles are the shared audit
// catalog (`@kortix/shared/audit-labels`: one per route and per event) and
// the named-action and path-pattern titles still written in
// audit-display-helpers.ts. A title enters the map only when English has its
// key; a title without one renders in English. The key stays the hash of the
// source title, and the English value may differ from it: copy edits change
// the value and keep the key, like every other `i18nComplete` string
// (2026-11-05: "project" became "workspace" in the values only).
//
//   node apps/web/scripts/generate-audit-title-keys.mjs
//   node apps/web/scripts/generate-audit-title-keys.mjs --check
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';
import { repositoryRoot, runFileGenerator } from './docs-generated-region.mjs';

const webRoot = resolve(repositoryRoot, 'apps/web');
const outputPath = resolve(webRoot, 'src/components/iam/audit-title-translation-keys.generated.ts');
const helpersPath = resolve(webRoot, 'src/components/iam/audit-display-helpers.ts');

export function translationKey(text) {
  return `text${createHash('sha256').update(text).digest('hex').slice(0, 12)}`;
}

/** String values of `title:` properties, and the catalogs' string literals. */
function stringLiterals(file, accept) {
  const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const values = new Set();
  function visit(node) {
    if (ts.isStringLiteralLike(node) && accept(node)) values.add(node.text);
    ts.forEachChild(node, visit);
  }
  visit(source);
  return values;
}

function isTitleValue(node) {
  const parent = node.parent;
  return (
    parent &&
    ((ts.isPropertyAssignment(parent) &&
      parent.initializer === node &&
      ts.isIdentifier(parent.name) &&
      parent.name.text === 'title') ||
      (ts.isConditionalExpression(parent) &&
        ts.isPropertyAssignment(parent.parent) &&
        ts.isIdentifier(parent.parent.name) &&
        parent.parent.name.text === 'title'))
  );
}

export function auditTitles() {
  const shared = resolve(repositoryRoot, 'packages/shared/src');
  const titles = new Set([
    ...stringLiterals(resolve(shared, 'audit-route-labels.ts'), isTitleValue),
    ...stringLiterals(resolve(shared, 'audit-labels.ts'), isTitleValue),
    ...stringLiterals(helpersPath, isTitleValue),
  ]);
  // Event lines are `'action': 'Title'`: the value of every property there.
  const events = stringLiterals(resolve(shared, 'audit-event-labels.ts'), (node) => {
    const parent = node.parent;
    return ts.isPropertyAssignment(parent) && parent.initializer === node;
  });
  for (const title of events) titles.add(title);
  return titles;
}

export function auditTitleTranslationKeys() {
  const english = JSON.parse(readFileSync(resolve(webRoot, 'translations/en.json'), 'utf8'))
    .hardcodedUi.i18nComplete;
  const entries = [...auditTitles()]
    .map((title) => [title, translationKey(title)])
    .filter(([, key]) => typeof english[key] === 'string')
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return Object.fromEntries(entries);
}

export function renderAuditTitleTranslationKeys() {
  const lines = Object.entries(auditTitleTranslationKeys()).map(
    ([title, key]) => `  ${JSON.stringify(title).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'").replace(/^/, "'").replace(/$/, "'")}: '${key}',`,
  );
  return (
    '// Generated by apps/web/scripts/generate-audit-title-keys.mjs. Do not edit directly.\n' +
    'export const AUDIT_TITLE_TRANSLATION_KEYS: Readonly<Record<string, string>> = {\n' +
    `${lines.join('\n')}\n};\n`
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await runFileGenerator(
    'the audit title translation keys',
    'node apps/web/scripts/generate-audit-title-keys.mjs',
    renderAuditTitleTranslationKeys,
    outputPath,
  );
}
