// Bundle the agent kit (agent-kit/) into convex/kit/bundle.generated.ts and
// write its content hash into agent-kit/kit.json. Run after any kit edit:
//   bun scripts/kit-bundle.ts          (write)
//   bun scripts/kit-bundle.ts --check  (exit 1 when the bundle or the hash is stale)
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const APP = join(import.meta.dir, '..');
const KIT = join(APP, 'agent-kit');
const OUT = join(APP, 'convex', 'kit', 'bundle.generated.ts');

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (name === '__pycache__' || name.startsWith('.')) return [];
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const rel = (p: string) => relative(KIT, p).split('\\').join('/');
const read = (p: string) => readFileSync(p, 'utf8');

/** Every file the hash covers: what changes agent behavior (not kit.json, the README or the eval set). */
export function kitFiles(): string[] {
  return walk(KIT).filter((p) => !['kit.json', 'README.md'].includes(rel(p)) && !rel(p).startsWith('evals/')).sort();
}

export function kitHash(): string {
  const h = createHash('sha256');
  for (const p of kitFiles()) h.update(`${rel(p)}\0${read(p)}\0`);
  return h.digest('hex').slice(0, 16);
}

/** Files installed into each firm's project repo: skills and the tool CLI (not fixtures or the selftest). */
function installFiles(): Array<{ path: string; content: string }> {
  return kitFiles()
    .map(rel)
    .filter((r) => r.startsWith('skills/') || (r.startsWith('lumen-kit/') && !r.startsWith('lumen-kit/fixtures/')))
    .filter((r) => r !== 'lumen-kit/lumen_kit/selftest.py')
    .map((r) => ({ path: r, content: read(join(KIT, r)) }));
}

export function bundleSource(): string {
  const version = JSON.parse(read(join(KIT, 'kit.json'))).version as string;
  const rules = read(join(KIT, 'agents', '_rules.md')).trim();
  const agents = Object.fromEntries(
    readdirSync(join(KIT, 'agents'))
      .filter((f) => f.endsWith('.md') && !f.startsWith('_'))
      .sort()
      .map((f) => [f.replace(/\.md$/, ''), `${rules}\n\n${read(join(KIT, 'agents', f)).trim()}\n`]),
  );
  const schemas = Object.fromEntries(
    readdirSync(join(KIT, 'lumen-kit', 'schemas'))
      .sort()
      .map((f) => [f.replace(/\.schema\.json$/, ''), JSON.parse(read(join(KIT, 'lumen-kit', 'schemas', f)))]),
  );
  const vectors = JSON.parse(read(join(KIT, 'shared', 'cite-vectors.json')));
  const data = { version, hash: kitHash(), agents, files: installFiles(), schemas, citeVectors: vectors.cases };
  return [
    '// GENERATED by scripts/kit-bundle.ts from agent-kit/. Do not edit. Run `bun scripts/kit-bundle.ts`.',
    '/* eslint-disable */',
    `export const KIT = ${JSON.stringify(data, null, 1)} as const;`,
    '',
  ].join('\n');
}

if (import.meta.main) {
  const check = process.argv.includes('--check');
  const kitJsonPath = join(KIT, 'kit.json');
  const kitJson = JSON.parse(read(kitJsonPath));
  const hash = kitHash();
  if (check) {
    let stale = false;
    try {
      stale = kitJson.hash !== hash || read(OUT) !== bundleSource();
    } catch {
      stale = true;
    }
    if (stale) {
      console.error('agent kit bundle is stale: run `bun scripts/kit-bundle.ts`');
      process.exit(1);
    }
    console.log(`kit ${kitJson.version} ${hash} up to date`);
  } else {
    writeFileSync(kitJsonPath, `${JSON.stringify({ ...kitJson, hash }, null, 2)}\n`);
    writeFileSync(OUT, bundleSource());
    console.log(`kit ${kitJson.version} ${hash}: ${OUT}`);
  }
}
